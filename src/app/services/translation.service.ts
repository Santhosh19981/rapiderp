  isRtl = computed(() => {
    const lang = this.currentLanguage();
    return lang === 'AR' || lang === 'UR';
  });

  setLanguage(lang: string): void {
    this.currentLanguage.set(lang);
    if (typeof document !== 'undefined') {
      const isRtl = lang === 'AR' || lang === 'UR';
      document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    }
  }

  translateModule(moduleId: string, fallback: string = ''): string {
    const lang = this.currentLanguage();
    return this.modules[lang]?.[moduleId] || this.modules['EN']?.[moduleId] || fallback;
  }

  translateSubModule(subModuleId: string, fallback: string = ''): string {
    const lang = this.currentLanguage();
    return this.subModules[lang]?.[subModuleId] || this.subModules['EN']?.[subModuleId] || fallback;
  }

  translate(key: string, fallback?: string): string {
    const lang = this.currentLanguage();
    return this.uiTexts[lang]?.[key] || this.uiTexts['EN']?.[key] || fallback || key;
  }
